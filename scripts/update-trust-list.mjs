// Regenerates src/lib/detect/trust-list.ts from the official C2PA Trust List
// (https://github.com/c2pa-org/conformance-public, CC BY 4.0).
// Usage: node scripts/update-trust-list.mjs [path-or-url-to-C2PA-TRUST-LIST.pem]
import fs from "node:fs/promises";

const DEFAULT_URL = "https://raw.githubusercontent.com/c2pa-org/conformance-public/main/trust-list/C2PA-TRUST-LIST.pem";
const src = process.argv[2] ?? DEFAULT_URL;
const pem = /^https?:/.test(src) ? await (await fetch(src)).text() : await fs.readFile(src, "utf8");
const certs = pem.match(/-----BEGIN CERTIFICATE-----[\s\S]+?-----END CERTIFICATE-----/g) ?? [];
if (certs.length === 0) throw new Error("No certificates found");
const out = `// Generated by scripts/update-trust-list.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Source: C2PA Trust List, https://github.com/c2pa-org/conformance-public (CC BY 4.0, © C2PA).
// ${certs.length} trust anchors.
export const C2PA_TRUST_ANCHORS = ${JSON.stringify(certs.join("\n") + "\n")};
`;
await fs.writeFile(new URL("../src/lib/detect/trust-list.ts", import.meta.url), out);
console.log(`Wrote ${certs.length} trust anchors.`);
